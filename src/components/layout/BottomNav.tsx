export default function BottomNav() {
  const pathname = usePathname();
  const { isSubUser } = useAuth();

  // Don't show nav on login page
  if (pathname === '/login') return null;

  // Sub-users cannot access Attendance sheets — admin only
  const visibleTabs = isSubUser
    ? tabs.filter((tab) => tab.path !== '/local-ladies-attendance')
    : tabs;

  return (
    <nav className="lg:hidden fixed bottom-0 left-0 right-0 z-40 bg-white border-t border-gray-200 shadow-[0_-4px_6px_-1px_rgba(0,0,0,0.05)]">
      <div className="max-w-lg mx-auto flex items-center justify-around h-16 pb-safe">
        {visibleTabs.map((tab) => {
          const isActive = tab.path === '/' ? pathname === '/' : pathname.startsWith(tab.path);
          return (
            <Link
              key={tab.path}
              href={tab.path}
              className={`flex flex-col items-center justify-center min-w-[48px] min-h-[48px] transition-colors duration-200 ${
                isActive ? 'text-teal-600' : 'text-gray-400'
              }`}
            >
              {tab.icon(isActive)}
              <span className={`text-[10px] font-medium mt-0.5 ${isActive ? 'text-teal-600' : 'text-gray-400'}`}>
                {tab.label}
              </span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}
